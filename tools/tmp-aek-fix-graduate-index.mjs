import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const target=path.join(ROOT,'functions/_lib/kb/graduate-catalog-2022.js');
let text=fs.readFileSync(target,'utf8');
const from=`const BY_CODE=new Map(GRADUATE_CATALOG_2022.map(item=>[item.code,item]));\nconst BY_NAME=new Map();\nfor(const item of GRADUATE_CATALOG_2022){\n  const list=BY_NAME.get(item.name)||[];\n  list.push(item);\n  BY_NAME.set(item.name,Object.freeze(list));\n}`;
const to=`const BY_CODE=new Map(GRADUATE_CATALOG_2022.map(item=>[item.code,item]));\nconst BY_NAME=new Map();\nfor(const item of GRADUATE_CATALOG_2022){\n  const list=BY_NAME.get(item.name)||[];\n  list.push(item);\n  BY_NAME.set(item.name,list);\n}`;
if(text.split(from).length-1!==1)throw new Error('graduate duplicate-name index patch did not match exactly once');
fs.writeFileSync(target,text.replace(from,to));
fs.rmSync(path.join(ROOT,'tools/tmp-aek-fix-graduate-index.mjs'));
console.log('graduate duplicate-name index fixed; temporary fixer removed');
