import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
await page.goto('http://127.0.0.1:4173/ln-rank/simulation-report.html', { waitUntil: 'networkidle', timeout: 30000 });
await page.waitForSelector('.volunteer-card', { timeout: 15000 });
if ((await page.locator('h1').first().innerText()) !== '模拟志愿工作台') throw new Error('v006 title missing');
if (await page.locator('.sheet-table:visible').count()) throw new Error('legacy table must not be visible');
if (await page.locator('.volunteer-card').count() !== 1) throw new Error('expected one initial editable volunteer');
const first = page.locator('.volunteer-card').first();
await first.locator('[data-field="school"]').fill('辽宁大学');
await first.locator('[data-field="majorCode"]').fill('080301');
await page.waitForTimeout(500);
const caption = await page.locator('.volunteer-card').first().locator('.major-caption').innerText();
if (caption.includes('尚未填写专业代码')) throw new Error(`major resolver did not update: ${caption}`);
await page.locator('.volunteer-card').first().getByRole('button', { name: /展开核对/ }).click();
if (!(await page.locator('.detail-panel').first().isVisible())) throw new Error('detail panel did not open');
if ((await page.locator('body').innerText()).includes('冲稳保')) throw new Error('forbidden legacy decision wording leaked into visible UI');
await page.getByRole('button', { name: '＋ 添加志愿' }).click();
await page.waitForTimeout(300);
if (await page.locator('.volunteer-card').count() !== 2) throw new Error('add volunteer failed');
const second = page.locator('.volunteer-card').nth(1);
await second.locator('[data-field="school"]').fill('大连理工大学');
await second.locator('[data-field="majorCode"]').fill('080301');
await page.waitForTimeout(300);
await second.getByRole('button', { name: '↑' }).click();
await page.waitForTimeout(300);
if ((await page.locator('.volunteer-card').first().locator('[data-field="school"]').inputValue()) !== '大连理工大学') throw new Error('reorder failed');
page.once('dialog', d => d.accept());
await page.locator('.volunteer-card').last().getByRole('button', { name: '删除' }).click();
await page.waitForTimeout(300);
if (await page.locator('.volunteer-card').count() !== 1) throw new Error('delete failed');
if (errors.length) throw new Error(`browser page errors: ${errors.join(' | ')}`);
await browser.close();
console.log('simulation-report-v006-browser: PASS');
