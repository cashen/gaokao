const fs = require('fs');
const path = require('path');
const root = process.cwd();
function read(p){return fs.readFileSync(path.join(root,p),'utf8')}
function exists(p){return fs.existsSync(path.join(root,p))}
const checks=[];
function check(name, ok, detail=''){checks.push({name,ok:!!ok,detail});}
check('不包含旧版 fenxi/index.html', !exists('fenxi/index.html'));
check('V3 index 存在', exists('fenxi/v3/index.html'));
check('版本为 rc2.fix2', /V3\.0\.0\.rc2\.fix2/.test(read('fenxi/v3/assets/js/version.v3.js')));
check('版本戳为 v300rc2fix2', /v300rc2fix2-20260512/.test(read('fenxi/v3/assets/js/version.v3.js')));
const compute=read('fenxi/v3/assets/js/adapters/compute-core.v3.js');
check('compute-core 基础池不叠加高级筛选', /基础候选池只做基础排序，不叠加候选复核页高级筛选/.test(compute));
check('compute-core hash 使用 base 不含 advanced', /hashState\(state\)\.base/.test(compute));
check('compute-core 结果标记 reviewFilterIsolated', /reviewFilterIsolated:true/.test(compute));
check('compute-core 保留位次先行 rankRole', /function rankRole/.test(compute)&&/超冲过远/.test(compute)&&/上限探索/.test(compute));
const adv=read('fenxi/v3/assets/js/adapters/advanced-filter-adapter.v3.js');
check('高级筛选有旧版 major 多字段语义', /function matchMajorLegacy/.test(adv)&&/majorMatchesV29475/.test(adv));
check('高级筛选有 primary 多字段语义', /function matchPrimaryLegacy/.test(adv)&&/officialMajorCode/.test(adv)&&/primaryDisciplineCodes/.test(adv));
check('高级筛选有漏斗诊断', /function buildFunnel/.test(adv)&&/bottleneck/.test(adv));
check('高级筛选支持目录可信度/院校层级/收费/易混/重点学科', /matchTax/.test(adv)&&/matchSchoolTier/.test(adv)&&/matchFee/.test(adv)&&/hasConfusable/.test(adv)&&/hasKeySubject/.test(adv));
const cand=read('fenxi/v3/assets/js/adapters/candidates-adapter-rc2.v3.js');
check('候选 adapter 在基础池上应用 view filter', /baseRows/.test(cand)&&/LN_V3_ADVANCED_FILTER\.apply/.test(cand));
check('候选 adapter 输出 baseTotal 和 visibleTotal', /baseTotal/.test(cand)&&/visibleTotal/.test(cand));
check('候选 adapter 不自动进自选', /只有手动加入后才进入家庭自选池/.test(cand));
const step=read('fenxi/v3/assets/js/steps/step-candidates-rc2.v3.js');
check('第6步显示基础候选池与当前筛选', /基础候选池/.test(step)&&/当前筛选/.test(step));
check('第6步有筛选漏斗', /候选筛选漏斗/.test(step)&&/funnelHtml/.test(step));
check('第6步有清空本页筛选/返回基础候选', /清空本页筛选/.test(step)&&/返回基础候选/.test(step));
check('第6步保留旧版卡片四要素', /招生身份/.test(step)&&/成本提醒/.test(step)&&/年度位次/.test(step)&&/位次角色/.test(step));
check('横向比较只读家庭自选池', /横向比较只读取家庭自选池/.test(step));
const inv=read('fenxi/v3/assets/js/adapters/state-invalidation-adapter.v3.js');
check('状态失效区分 base 与 advanced', /base:base/.test(inv)&&/advanced:advanced/.test(inv));
check('位次/家庭变化清空候选复核筛选', /clearReviewFilter/.test(inv)&&/clearReview=true/.test(inv));
const debug=read('fenxi/v3/assets/js/debug/path-matrix-debug.v3.js');
check('Debug 为 rc2.fix2', /RC2\.fix2/.test(debug));
check('Debug 有候选筛选隔离测试', /reviewFilterIsolation/.test(debug)&&/候选复核筛选可压成0但不污染基础池/.test(debug));
const css=read('fenxi/v3/assets/css/rc2-core.v3.css');
check('CSS 有漏斗与0结果提示样式', /rc2-review-funnel/.test(css)&&/rc2-zero-filter/.test(css));
const failed=checks.filter(x=>!x.ok);
for(const [i,c] of checks.entries()) console.log(`${c.ok?'PASS':'FAIL'} ${String(i+1).padStart(2,'0')} ${c.name}${c.detail?' '+c.detail:''}`);
if(failed.length){console.error(`\nFAILED ${failed.length}/${checks.length}`);process.exit(1);}else console.log(`\nOK ${checks.length}/${checks.length}`);
