import { strict as assert } from 'node:assert';
import { chromium } from 'playwright';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const pageErrors=[];
page.on('pageerror',error=>pageErrors.push(error));
page.on('console',message=>{if(message.type()==='error')console.error(`[browser-console] ${message.text()}`);});
await page.route('**/api/simulation-rank**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,rank:12345,available:true})}));
await page.route('**/api/ai/major-history**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,records:[{id:'ln-test-shenyang-polymer',school:'沈阳化工大学',major:'高分子材料与工程',majorCode2026:'01',standardMajorName:'高分子材料与工程',standardMajorCode:'080407',score2026:523,rank2026:34567,score2025:518,rank2025:35200,score2024:510,rank2024:36800}]})}));
await page.goto('http://127.0.0.1:4173/ln-rank/simulation-report.html',{waitUntil:'domcontentloaded'});
await page.locator('h1').filter({hasText:'模拟志愿'}).waitFor();
const initialCards=await page.locator('.volunteer-card').count();
if(initialCards!==1){
  console.error('[browser-diagnostic] initialCards=',initialCards);
  console.error('[browser-diagnostic] pageErrors=',pageErrors.map(error=>error.stack||String(error)).join('\n---\n'));
  console.error('[browser-diagnostic] runtime=',await page.evaluate(()=>({runtime:Boolean(window.GAOKAO_SIMULATION_RUNTIME),html:document.querySelector('#wbRows')?.innerHTML||''})));
}
assert.equal(initialCards,1);
await page.locator('#wbTotalScore').fill('555');
await page.waitForTimeout(180);
assert.equal(await page.locator('#wbRank').textContent(),'12,345');
const firstSchool=page.locator('[data-field="school"]').first();
await firstSchool.fill('沈阳化工大学');
await page.waitForTimeout(120);
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('gaokao:simulation-report:v002'));s.volunteers[0].school='沈阳化工大学';s.volunteers[0].confirmedSchool='沈阳化工大学';localStorage.setItem('gaokao:simulation-report:v002',JSON.stringify(s));});
await page.reload({waitUntil:'domcontentloaded'});
await page.locator('#wbAdd').click();
await page.locator('.volunteer-card').nth(1).waitFor({state:'visible'});
assert.equal(await page.locator('.volunteer-card').count(),2);
const secondSchool=page.locator('[data-field="school"]').nth(1);
await secondSchool.fill('辽宁');
await secondSchool.fill('沈阳');
await secondSchool.fill('沈阳化工大学');
await secondSchool.fill('');
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('gaokao:simulation-report:v002'));s.volunteers[0].school='沈阳化工大学';s.volunteers[0].confirmedSchool='沈阳化工大学';localStorage.setItem('gaokao:simulation-report:v002',JSON.stringify(s));});
await page.reload({waitUntil:'domcontentloaded'});
const schoolCard=page.locator('.volunteer-card').filter({has:page.locator('[data-field="school"][value="沈阳化工大学"]')}).first();
await schoolCard.waitFor({state:'visible'});
const firstMajor=schoolCard.locator('[data-field="majorCode"]');
await firstMajor.fill('高分子');
await schoolCard.locator('.candidate').filter({hasText:'高分子材料与工程'}).first().waitFor({state:'visible',timeout:5000});
await schoolCard.locator('.candidate').filter({hasText:'高分子材料与工程'}).first().click();
await page.waitForTimeout(180);
assert.ok((await schoolCard.locator('.history-grid').textContent()).includes('2026'));
await schoolCard.locator('[data-family="候选"]').click();
assert.equal(await schoolCard.locator('[data-family="候选"]').getAttribute('aria-pressed'),'true');
await page.locator('[data-action="up"]').nth(1).click();
await page.reload({waitUntil:'domcontentloaded'});
assert.equal(await page.locator('.volunteer-card').count(),2);
const persistedSchool=page.locator('[data-field="school"][value="沈阳化工大学"]');
await persistedSchool.waitFor({state:'visible'});
const persistedCard=persistedSchool.locator('xpath=ancestor::article[contains(@class,"volunteer-card")]');
assert.equal(await persistedCard.locator('[data-family="候选"]').getAttribute('aria-pressed'),'true');
console.log('simulation unified browser contract: PASS');
await browser.close();
