import { strict as assert } from 'node:assert';
import { chromium } from 'playwright';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.route('**/api/simulation-rank**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,rank:12345,available:true})}));
await page.route('**/api/ai/major-history**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,records:[{school:'沈阳化工大学',standardMajorName:'高分子材料与工程',standardMajorCode:'080407',score2026:523,rank2026:34567,score2025:518,rank2025:35200,score2024:510,rank2024:36800}]})}));
await page.goto('http://127.0.0.1:4173/ln-rank/simulation-report.html',{waitUntil:'domcontentloaded'});
await page.locator('h1').filter({hasText:'模拟志愿'}).waitFor();
assert.equal(await page.locator('.volunteer-card').count(),1);
await page.locator('#wbTotalScore').fill('555');
await page.waitForTimeout(180);
assert.equal(await page.locator('#wbRank').textContent(),'12,345');
await page.locator('#wbAdd').click();
assert.equal(await page.locator('.volunteer-card').count(),2);
const firstSchool=page.locator('[data-field="school"]').first();
const firstMajor=page.locator('[data-field="majorCode"]').first();
const t0=await page.evaluate(()=>performance.now());
await firstSchool.fill('辽宁');
await firstSchool.fill('沈阳');
await firstSchool.fill('沈阳化工大学');
await firstSchool.fill('');
const t1=await page.evaluate(()=>performance.now());
assert.ok(t1-t0<250,'rapid school editing must stay synchronous and responsive');
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('gaokao:simulation-report:v002'));s.volunteers[0].school='沈阳化工大学';s.volunteers[0].confirmedSchool='沈阳化工大学';localStorage.setItem('gaokao:simulation-report:v002',JSON.stringify(s));});
await page.reload({waitUntil:'domcontentloaded'});
await firstMajor.fill('高分子');
await page.waitForTimeout(260);
assert.ok(await page.locator('.candidate').filter({hasText:'高分子材料与工程'}).count()>=1);
await page.locator('.candidate').filter({hasText:'高分子材料与工程'}).first().click();
await page.waitForTimeout(120);
assert.ok((await page.locator('.history-inline').first().textContent()).includes('2026'));
await page.locator('[data-family="候选"]').first().click();
assert.equal(await page.locator('[data-family="候选"]').first().getAttribute('aria-pressed'),'true');
await page.locator('[data-action="up"]').nth(1).click();
await page.reload({waitUntil:'domcontentloaded'});
assert.equal(await page.locator('.volunteer-card').count(),2);
assert.equal(await page.locator('[data-family="候选"]').first().getAttribute('aria-pressed'),'true');
console.log('simulation unified browser contract: PASS');
await browser.close();
