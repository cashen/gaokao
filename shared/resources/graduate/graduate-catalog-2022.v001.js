function parseLine(line) {
  const [disciplineCode, disciplineName, code, name, typeFlag, ...notes] = line.split('|');
  const mastersOnly = notes.includes('M');
  const note = notes.filter(item => item && item !== 'M').join('；');
  return Object.freeze({
    disciplineCode,
    disciplineName,
    code,
    name,
    kind: typeFlag === 'P' ? 'professional_degree' : 'academic_discipline',
    mastersOnly,
    note,
    catalogVersion: '2022',
    effectiveFrom: 2023,
    sourceId: 'catalog2022'
  });
}

export const GRADUATE_CATALOG_2022 = Object.freeze(RAW.split('\n').map(parseLine));
const BY_CODE = new Map(GRADUATE_CATALOG_2022.map(item => [item.code, item]));

