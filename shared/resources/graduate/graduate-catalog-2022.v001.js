export function getGraduateCatalogEntry(code) {
  return BY_CODE.get(String(code || '').trim()) || null;
}

export function getGraduateEntriesByCodes(codes = []) {
  return [...new Set((codes || []).map(code => String(code || '').trim()).filter(Boolean))]
    .map(getGraduateCatalogEntry)
    .filter(Boolean);
}

