function unique(values = []) {
  return [...new Set(values.filter(Boolean))];
}

function fieldRecords(codes = []) {
  const all = Object.values(PROFESSIONAL_FIELD_EVIDENCE_2026).flat();
  return unique(codes).map(code => all.find(item => item.code === code)).filter(Boolean);
}

function classify(entries) {
  return {
    academic: entries.filter(item => item.kind === 'academic_discipline'),
    professional: entries.filter(item => item.kind === 'professional_degree')
  };
}

export function buildUndergradGraduatePathway(major = {}) {
  const name = String(major.name || major.major || '').trim();
  const majorClass = String(major.majorClass || major.categoryName || '').trim();
  const exact = MAJOR_RULES.get(name) || null;
  const classCodes = CLASS_RULES.get(majorClass) || [];
  const codes = unique([...(exact?.codes || []), ...classCodes]);
  const entries = getGraduateEntriesByCodes(codes);
  const grouped = classify(entries);
  const fields = fieldRecords(exact?.fields || []);
  const curated = Boolean(exact || classCodes.length);
  return Object.freeze({
    version: UNDERGRAD_GRADUATE_PATHWAY_META.version,
    undergraduate: Object.freeze({
      code: String(major.code || '').trim(),
      name,
      discipline: String(major.discipline || '').trim(),
      majorClass
    }),
    relationStatus: curated ? 'curated_navigation' : 'no_national_one_to_one',
    academic: Object.freeze(grouped.academic),
    professional: Object.freeze(grouped.professional),
    professionalFields: Object.freeze(fields),
    note: exact?.note || (curated
      ? '以下是基于国家目录实体和学科知识结构整理的升学导航，不代表教育部规定的本科→硕士一一对应关系。'
      : '国家目录未规定该本科专业与某个研究生一级学科/专业学位类别固定对应。建议结合目标院校当年硕士招生专业目录、考试科目和前置专业要求核验。'),
    boundary: UNDERGRAD_GRADUATE_PATHWAY_META.boundary
  });
}
